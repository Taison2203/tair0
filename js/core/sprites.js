/**
 * sprites.js — ASCII-art sprite renderer.
 * Format: array of strings (rows) + palette mapping char → CSS variable name.
 * Produces a <canvas class="px"> sized with CSS calc for pixel-perfect scaling.
 */

import { css } from './dom.js?v=ezic-1';

/** Cache of resolved CSS colors so we don't call getComputedStyle per pixel. */
const colorCache = new Map();

function resolveColor(varName) {
  if (colorCache.has(varName)) return colorCache.get(varName);
  const c = css(varName);
  colorCache.set(varName, c);
  return c;
}

/**
 * Draw an ASCII sprite to a new canvas.
 * @param {string[]} rows - array of strings, each char is a pixel
 * @param {Object<string,string>} pal - char → CSS variable (e.g. '#': '--metal')
 * @returns {HTMLCanvasElement}
 */
export function drawSprite(rows, pal) {
  const h = rows.length;
  const w = Math.max(...rows.map((r) => r.length));
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  canvas.className = 'px';
  canvas.style.width = `calc(${w} * var(--u))`;
  canvas.style.height = `calc(${h} * var(--u))`;
  canvas.setAttribute('aria-hidden', 'true');
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < rows[y].length; x++) {
      const ch = rows[y][x];
      if (ch === '.' || ch === ' ') continue;
      const varName = pal[ch];
      if (!varName) continue;
      ctx.fillStyle = resolveColor(varName);
      ctx.fillRect(x, y, 1, 1);
    }
  }
  return canvas;
}

/**
 * Generate a tileable texture canvas.
 * @param {number} w - width in pixels
 * @param {number} h - height in pixels
 * @param {function} paintFn - (ctx, w, h) => void
 * @returns {HTMLCanvasElement}
 */
export function makeTile(w, h, paintFn) {
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const ctx = c.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  paintFn(ctx, w, h);
  return c;
}

